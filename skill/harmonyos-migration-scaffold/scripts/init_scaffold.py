def load_feature_map(path: Path) -> dict[str, Any]:
    """读取并校验 feature-map.json（v3 必需输入，Phase 2 权威 schema）。"""
    data = require_object(load_json(path), "feature-map.json")
    if data.get("schema_version") != 1:
        raise ValueError("feature-map.json schema_version must be 1")
    features = data.get("features")
    if not isinstance(features, list) or not features:
        raise ValueError("feature-map.json features must be a non-empty array")
    coverage = require_object(data.get("coverage_gate"), "feature-map coverage_gate")
    if coverage.get("included_features_covered") is not True:
        raise ValueError("feature-map coverage_gate is not covered")
    seen_features: set[str] = set()
    seen_surfaces: set[str] = set()
    normalized: list[dict[str, Any]] = []
    for feature in features:
        if not isinstance(feature, dict):
            raise ValueError("feature-map features[] entries must be objects")
        feature_id = str(feature.get("feature_id", "")).strip()
        validate_id(feature_id, "Feature-ID in feature-map")
        if feature_id in seen_features:
            raise ValueError(f"Duplicate feature-map Feature-ID: {feature_id}")
        seen_features.add(feature_id)
        surfaces: list[dict[str, Any]] = []
        for surface in feature.get("surfaces") or []:
            if not isinstance(surface, dict):
                raise ValueError(f"{feature_id}: surfaces[] entries must be objects")
            surface_id = str(surface.get("id", "")).strip()
            validate_id(surface_id, "Surface-ID in feature-map")
            if surface_id in seen_surfaces:
                # GD-P3-05: a behavior-host entry is a reference to an already
                # declared surface (component features delegate their carrier
                # to the host page); duplicates are rejected otherwise.
                if str(surface.get("relation", "")).strip() != "behavior-host":
                    raise ValueError(f"Duplicate feature-map Surface-ID: {surface_id}")
                continue
            seen_surfaces.add(surface_id)
            kind = str(surface.get("kind", "")).strip()
            if kind not in V3_SURFACE_KINDS:
                raise ValueError(f"{surface_id}: unknown surface kind {kind!r}")
            is_container = surface.get("is_container") is True
            if is_container != (kind == "container"):
                raise ValueError(f"{surface_id}: is_container must agree with kind=='container'")
            surfaces.append({"id": surface_id, "kind": kind, "is_container": is_container})
        normalized.append({"feature_id": feature_id, "surfaces": surfaces})
    included = [str(item) for item in coverage.get("included", [])]
    if sorted(included) != sorted(seen_features):
        raise ValueError("feature-map coverage_gate.included differs from features[] ids")
    return {
        "feature_count": len(normalized),
        "surface_count": sum(len(f["surfaces"]) for f in normalized),
        "included": included,
        "features": normalized,
    }


def build_surface_plan(
    feature_map: dict[str, Any],
    navigation_relations: list[dict[str, str]],
) -> dict[str, Any]:
    """feature-map surfaces → 确定性骨架计划（route / modal@host / none）。

    page → 路由节点+页面壳；sheet/dialog/menu → 模态载体，宿主三层确定性
    推断（不发明拓扑，来源全部记录在 mount_host_source）：
      1. nav-explicit-edge：跳转边 to==modal surface 且 from==page surface；
      2. feature-page：同 feature 恰有一个 page surface；
      3. fallback-sorted-first-route：排序后首个路由面（无路由面则 unresolved）。
    container/reusable-component → passthrough（不生成壳，Phase 4 透明宿主）。
    跳转边仅当两端都精确命中 surface 清单才保留（真实 run 中 nav 表页面
    哈希与 feature-map 不同轮次，交集可能为 0——如实保留计数，不报错）。
    """
    surfaces: list[dict[str, Any]] = []
    seen_surface_ids: set[str] = set()
    for feature in feature_map["features"]:
        for surface in feature["surfaces"]:
            # GD-P3-05: one shell per surface (first declaration wins). A
            # behavior-host entry references an existing surface and must not
            # duplicate the shell plan or the input-lock surfaces array.
            if surface["id"] in seen_surface_ids:
                continue
            seen_surface_ids.add(surface["id"])
            surfaces.append({**surface, "feature_id": feature["feature_id"]})
    by_id = {surface["id"]: surface for surface in surfaces}
    route_rows = sorted(
        (s for s in surfaces if s["kind"] == "page"), key=lambda s: s["id"]
    )
    route_ids = {s["id"] for s in route_rows}
    modal_ids = {s["id"] for s in surfaces if s["kind"] in V3_MODAL_KINDS}

    host_edges: dict[str, set[str]] = {}
    kept_edges: list[dict[str, str]] = []
    skipped_nav_pages: set[str] = set()
    nav_pages: set[str] = set()
    for row in navigation_relations:
        from_id = str(row.get("from_page_id", "")).strip()
        to_id = str(row.get("to_page_id", "")).strip()
        for page_id in (from_id, to_id):
            if page_id:
                nav_pages.add(page_id)
        if from_id in by_id and to_id in by_id:
            kept_edges.append(
                {
                    "candidate_id": str(row.get("candidate_id", "")).strip(),
                    "from_surface_id": from_id,
                    "to_surface_id": to_id,
                    "from_kind": by_id[from_id]["kind"],
                    "to_kind": by_id[to_id]["kind"],
                    "relation_type": str(row.get("relation_type", "")).strip(),
                    "source_ref": str(row.get("source_ref", "")).strip(),
                }
            )
            if to_id in modal_ids and from_id in route_ids:
                host_edges.setdefault(to_id, set()).add(from_id)
    skipped_nav_pages = nav_pages - set(by_id)

    feature_pages: dict[str, list[str]] = {}
    for surface in route_rows:
        feature_pages.setdefault(surface["feature_id"], []).append(surface["id"])

    routes: list[dict[str, Any]] = []
    modals: list[dict[str, Any]] = []
    passthrough: list[dict[str, Any]] = []
    for surface in sorted(surfaces, key=lambda s: s["id"]):
        surface_id = surface["id"]
        kind = surface["kind"]
        if kind == "page":
            symbol = page_shell_symbol(surface_id)
            routes.append(
                {
                    "surface_id": surface_id,
                    "feature_id": surface["feature_id"],
                    "kind": kind,
                    "route_id": surface_id,
                    "shell_symbol": symbol,
                    "shell_file": f"{PAGE_SHELL_DIR}/{symbol}.ets",
                }
            )
        elif kind in V3_MODAL_KINDS:
            symbol = modal_shell_symbol(surface_id)
            candidates = sorted(host_edges.get(surface_id, set()))
            if candidates:
                host, host_source = candidates[0], "nav-explicit-edge"
                host_candidates = candidates
            elif len(feature_pages.get(surface["feature_id"], [])) == 1:
                host = feature_pages[surface["feature_id"]][0]
                host_source, host_candidates = "feature-page", [host]
            elif route_ids:
                host = sorted(route_ids)[0]
                host_source, host_candidates = "fallback-sorted-first-route", [host]
            else:
                host, host_source, host_candidates = None, "unresolved-no-route-surface", []
            modals.append(
                {
                    "surface_id": surface_id,
                    "feature_id": surface["feature_id"],
                    "kind": kind,
                    "shell_symbol": symbol,
                    "shell_file": f"{V3_MODAL_SHELL_DIR}/{symbol}.ets",
                    "host_surface_id": host,
                    "mount_host_source": host_source,
                    "host_candidates": host_candidates,
                }
            )
        else:
            passthrough.append(
                {
                    "surface_id": surface_id,
                    "feature_id": surface["feature_id"],
                    "kind": kind,
                    "reason": (
                        "transparent-container-host" if kind == "container"
                        else f"no-shell-kind:{kind}"
                    ),
                }
            )
    return {
        "schema_version": 1,
        "paradigm": V3_PARADIGM,
        "routes": routes,
        "modals": modals,
        "passthrough": passthrough,
        "edges": sorted(
            kept_edges,
            key=lambda e: (e["from_surface_id"], e["to_surface_id"], e["candidate_id"]),
        ),
        "skipped_nav_pages": sorted(skipped_nav_pages),
        "stats": {
            "surface_count": len(surfaces),
            "route_count": len(routes),
            "modal_count": len(modals),
            "passthrough_count": len(passthrough),
            "nav_row_count": len(navigation_relations),
            "nav_edge_kept": len(kept_edges),
            "nav_pages_skipped": len(skipped_nav_pages),
        },
    }


def surface_lock_entries(plan: dict[str, Any]) -> list[dict[str, Any]]:
    """骨架计划 → input-lock v3 的 surfaces[]（含 route_or_mount 三态值）。"""
    entries: list[dict[str, Any]] = []
    for route in plan["routes"]:
        entries.append(
            {
                "id": route["surface_id"], "kind": route["kind"], "is_container": False,
                "route_or_mount": "route", "feature_id": route["feature_id"],
                "shell_symbol": route["shell_symbol"], "shell_file": route["shell_file"],
                "mount_host_source": None,
            }
        )
    for modal in plan["modals"]:
        host = modal["host_surface_id"]
        entries.append(
            {
                "id": modal["surface_id"], "kind": modal["kind"], "is_container": False,
                "route_or_mount": f"modal@{host}" if host else "modal@UNRESOLVED",
                "feature_id": modal["feature_id"],
                "shell_symbol": modal["shell_symbol"], "shell_file": modal["shell_file"],
                "mount_host_source": modal["mount_host_source"],
            }
        )
    for item in plan["passthrough"]:
        entries.append(
            {
                "id": item["surface_id"], "kind": item["kind"],
                "is_container": item["kind"] == "container",
                "route_or_mount": "none", "feature_id": item["feature_id"],
                "shell_symbol": None, "shell_file": None,
                "mount_host_source": None,
            }
        )
    return sorted(entries, key=lambda entry: entry["id"])


