# content_descs 携带 Tab/FAB 特征）+ global_palette（主色板）。
# 政策：UI_FIDELITY=HIGH 的机械表达 = preserve 段逐项列出必须保留的
# 文本/入口/状态/色板；custom_allowed 默认 no，仅系统组件确实无法表达
