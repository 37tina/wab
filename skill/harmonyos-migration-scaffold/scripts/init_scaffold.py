def page_shell_symbol(page_id: str) -> str:
    """从 Page-ID 确定性派生页面壳 ArkTS struct 名（无随机性，可重放）。"""
    parts = page_id.split("-")
    if parts and parts[0] == "PAGE":
        parts = parts[1:]
    name = "".join(part.capitalize() for part in parts if part)
    return f"ShellPage{name}"


