# content_descs 命中 >= TAB_HINT_MIN_HITS 个 → 底栏 Tabs 特征。
TAB_HINT_DESCRIPTORS = frozenset({
    "待办事项", "日历视图", "进展", "待办", "日历", "任务", "日程",
    "首页", "消息", "我的", "设置", "收藏",
})
TAB_HINT_MIN_HITS = 3
# class_histogram 中可识别的底栏导航容器类（子串匹配）。
TAB_NAVIGATION_CLASSES = ("BottomNavigationView", "TabLayout", "NavigationBarView", "BottomBar")
# 自绘/特效宿主类 → custom_allowed=yes 的唯一机械通道。
CUSTOM_DRAW_CLASSES = ("SurfaceView", "TextureView", "GLSurfaceView")
# FAB 特征（content_descs 子串命中，进 android_structure 描述与 preserve）。
FAB_HINT_DESCRIPTORS = ("添加新", "新建", "添加")
# preserve 段采样上限（防超长随机串/噪声撑爆契约）。
PRESERVE_MAX_TEXTS = 12
PRESERVE_MAX_DESCS = 10
PRESERVE_MAX_PALETTE = 4
PRESERVE_TEXT_MAX_LEN = 24

# 映射规则表（kind × 特征 → native_component）的规则名（登记进每项
# matched_rule，供人工审计追溯判定路径）。
RULE_PAGE_TABS = "page+bottom-tabs"
RULE_PAGE_PLAIN = "page+plain-content"
RULE_SHEET = "sheet"
RULE_DIALOG = "dialog"
RULE_MENU = "menu"
RULE_PASSTHROUGH = "container/component-passthrough"


# 主入口页命名标记（Android 主 Activity 命名惯例：Home/Main/Launcher；
# 用于多 page 共享同一快照证据时仲裁底栏 Tabs 唯一持有者）。
PRIMARY_PAGE_MARKERS = ("HOME", "MAIN", "LAUNCHER")


def _tab_bar_signature(
    android_structure_hints: dict[str, Any],
) -> tuple[str | None, int]:
    """底栏导航特征检测：class_histogram 导航容器类优先，次选
    content_descs 命中 TAB_HINT_DESCRIPTORS >= 3。

    返回 (命中证据描述 | None, 强度)。强度用于 plan 级唯一持有者仲裁：
    导航容器类命中 = 999（结构证据最强）；词命中 = 命中词数。纯函数无 IO。
    """
    histogram = android_structure_hints.get("class_histogram")
    if isinstance(histogram, dict):
        for cls in histogram:
            if any(nav in str(cls) for nav in TAB_NAVIGATION_CLASSES):
                return f"class_histogram:{cls}", 999
    descs = android_structure_hints.get("content_descs")
    if isinstance(descs, list):
        hits = sorted(
            {str(d) for d in descs if str(d) in TAB_HINT_DESCRIPTORS}
        )
        if len(hits) >= TAB_HINT_MIN_HITS:
            return "content_descs:" + "+".join(hits), len(hits)
    return None, 0


def map_native_component(kind: str, android_structure_hints: dict[str, Any] | None) -> str:
    """映射规则表（纯函数，可单测）：kind × Android 结构特征 → HarmonyOS
    原生组件组合。

    - page + 底栏导航特征 → Navigation+NavPathStack+Tabs(barPosition=End)
      +List+LazyForEach（三 Tab 主页形态）
    - page + 普通内容    → Navigation+NavPathStack+List/Scroll
    - sheet              → bindSheet(detents MEDIUM/LARGE)
    - dialog             → CustomDialog/bindMenu
    - menu               → bindMenu
    - container/component → none (透传)（Phase 4 透明宿主）
    """
    hints = android_structure_hints if isinstance(android_structure_hints, dict) else {}
    if kind == "page":
        signature, _strength = _tab_bar_signature(hints)
        if signature is not None:
            return "Navigation+NavPathStack+Tabs(barPosition=End)+List+LazyForEach"
        return "Navigation+NavPathStack+List/Scroll"
    if kind == "sheet":
        return "bindSheet(detents MEDIUM/LARGE)"
    if kind == "dialog":
        return "CustomDialog/bindMenu"
    if kind == "menu":
        return "bindMenu"
    return "none (透传)"


def _matched_rule(kind: str, hints: dict[str, Any]) -> str:
    if kind == "page":
        signature, _strength = _tab_bar_signature(hints)
        return RULE_PAGE_TABS if signature is not None else RULE_PAGE_PLAIN
    if kind in V3_MODAL_KINDS:
        return {"sheet": RULE_SHEET, "dialog": RULE_DIALOG, "menu": RULE_MENU}[kind]
    return RULE_PASSTHROUGH


def _android_structure_sentence(surface_id: str, ui_tree_summary: dict[str, Any] | None) -> str:
    """ui_tree_summary → 一句话 Android 主要视觉结构描述（确定性）。"""
    if not isinstance(ui_tree_summary, dict) or not ui_tree_summary:
        return (
            "visual-memory 未覆盖该 surface 的 ui_tree_summary"
            "（Phase 2 无对应运行时快照），结构描述退化"
        )
    parts: list[str] = []
    histogram = ui_tree_summary.get("class_histogram")
    if isinstance(histogram, dict) and histogram:
        ranked = sorted(histogram.items(), key=lambda kv: (-kv[1], kv[0]))
        head = "、".join(
            f"{cls}×{count}" if count > 1 else cls for cls, count in ranked[:4]
        )
        parts.append(f"主要类：{head}")
    if any("ComposeView" in str(cls) for cls in (histogram or {})):
        parts.append("ComposeView 宿主")
    node_count = ui_tree_summary.get("node_count")
    depth = ui_tree_summary.get("depth_max")
    if isinstance(node_count, int) and isinstance(depth, int):
        parts.append(f"{node_count} 节点/最大深度 {depth}")
    descs = ui_tree_summary.get("content_descs")
    if isinstance(descs, list):
        fab = next(
            (d for d in descs if any(hint in str(d) for hint in FAB_HINT_DESCRIPTORS)),
            None,
        )
        if fab is not None:
            parts.append(f"FAB（{fab}）")
    return f"{surface_id}：" + "；".join(parts) if parts else f"{surface_id}：结构摘要为空"


def _preserve_contract(
    ui_tree_summary: dict[str, Any] | None, global_palette: dict[str, Any] | None
) -> dict[str, Any]:
    """UI_FIDELITY=HIGH 的机械表达：必须保留的文本/入口/状态/色板清单。

    从 visual-memory 的 visible_texts（状态/文案）+ content_descs（操作
    入口）+ global_palette（主配色）确定性采样；来源不可用时清单为空但
    note 说明退化（policy 字段保持恒非空）。
    """
    texts: list[str] = []
    descs: list[str] = []
    summary = ui_tree_summary if isinstance(ui_tree_summary, dict) else {}
    for text in summary.get("visible_texts") or []:
        text = str(text).strip()
        if text and len(text) <= PRESERVE_TEXT_MAX_LEN and text not in texts:
            texts.append(text)
        if len(texts) >= PRESERVE_MAX_TEXTS:
            break
    for desc in summary.get("content_descs") or []:
        desc = str(desc).strip()
        if desc and desc != "无" and desc not in descs:
            descs.append(desc)
        if len(descs) >= PRESERVE_MAX_DESCS:
            break
    palette: list[dict[str, str]] = []
    if isinstance(global_palette, dict):
        for group in ("background_colors", "theme_colors"):
            for swatch in global_palette.get(group) or []:
                if isinstance(swatch, dict) and swatch.get("name") and swatch.get("hex"):
                    palette.append(
                        {"name": str(swatch["name"]), "hex": str(swatch["hex"])}
                    )
                if len(palette) >= PRESERVE_MAX_PALETTE:
                    break
            if len(palette) >= PRESERVE_MAX_PALETTE:
                break
    available = bool(texts or descs or palette)
    return {
        "policy": "UI_FIDELITY=HIGH",
        "texts": texts,
        "content_descs": descs,
        "palette": palette,
        "note": (
            "原生重表达必须保留以上可见文本/无障碍入口/主色板"
            if available
            else "visual-memory 对该 surface 无可用证据（无快照或无色板），"
                 "保留要求退化为 feature-map surface 声明本身"
        ),
    }


def _native_carrier_note(route_or_mount: str) -> str:
    """route_or_mount 三态 → 人类可读的 HarmonyOS 承载说明。"""
    if route_or_mount == "route":
        return "route：Navigation 路由节点（独立页面，NavDestination 承载）"
    if route_or_mount.startswith("modal@"):
        host = route_or_mount.split("@", 1)[1]
        return (
            f"modal@{host}：以 bindSheet/CustomDialog 模态挂载于宿主页面 {host}"
        )
    return "none：透传（不生成壳，Phase 4 透明宿主组合进宿主页面）"


def _visual_memory_surface_index(
    visual_memory: dict[str, Any] | None,
) -> dict[str, dict[str, Any]]:
    """visual-memory.surfaces → {surface_id: ui_tree_summary}（缺失退化为空）。"""
    index: dict[str, dict[str, Any]] = {}
    if isinstance(visual_memory, dict):
        for surface in visual_memory.get("surfaces") or []:
            if isinstance(surface, dict) and surface.get("surface_id"):
                index[str(surface["surface_id"])] = (
                    surface.get("ui_tree_summary")
                    if isinstance(surface.get("ui_tree_summary"), dict)
                    else {}
                )
    return index


def _elect_tabs_owner(
    routes: list[dict[str, Any]],
    surface_index: dict[str, dict[str, Any]],
    edges: list[dict[str, Any]],
) -> tuple[str | None, list[str]]:
    """底栏 Tabs 唯一持有者仲裁（一个 Navigation 体系只有一个底栏 Tabs）。

    背景：Phase 2 的 BC after 快照可能让多个 page 共享同一份主页状态
    证据（如 DETAILSCREEN 与 HOMESCREEN 的 content_descs 相同），词特征
    同时命中。机械仲裁（确定性，从强到弱）：
      1. 特征强度（导航容器类 > 更多词命中）；
      2. surface_id 含主入口标记（HOME/MAIN/LAUNCHER，Android 主
         Activity 命名惯例）；
      3. nav 边出度大者（导航源头）；
      4. 字典序最小。
    返回 (owner_surface_id | None, 全部命中特征的 page id 列表)。
    """
    scored: list[tuple[int, str]] = []
    for route in routes:
        summary = surface_index.get(route["surface_id"]) or {}
        hints = {
            "class_histogram": summary.get("class_histogram"),
            "content_descs": summary.get("content_descs"),
        }
        _signature, strength = _tab_bar_signature(hints)
        if strength > 0:
            scored.append((strength, route["surface_id"]))
    if not scored:
        return None, []
    detected = sorted(sid for _s, sid in scored)
    out_degree: dict[str, int] = {}
    for edge in edges:
        out_degree[str(edge.get("from_surface_id", ""))] = (
            out_degree.get(str(edge.get("from_surface_id", "")), 0) + 1
        )

    def _rank(item: tuple[int, str]) -> tuple[int, int, int, str]:
        strength, surface_id = item
        marker = any(m in surface_id.upper() for m in PRIMARY_PAGE_MARKERS)
        return (-strength, 0 if marker else 1, -out_degree.get(surface_id, 0), surface_id)

    owner = min(scored, key=_rank)[1]
    return owner, detected


def attach_ui_blueprint(
    plan: dict[str, Any],
    visual_memory: dict[str, Any] | None,
    visual_memory_source: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """surface-plan 三段（routes/modals/passthrough）原地追加 UI 蓝图字段。

    每 surface 平铺六字段：android_structure / preserve / native_carrier /
    native_component / custom_allowed / reason（+matched_rule 审计追溯）。
    返回顶层 ui_blueprint 摘要（由调用方写入 plan["ui_blueprint"]）。
    """
    surface_index = _visual_memory_surface_index(visual_memory)
    global_palette = (
        visual_memory.get("global_palette")
        if isinstance(visual_memory, dict)
           and isinstance(visual_memory.get("global_palette"), dict)
        else None
    )
    covered = 0
    blueprinted = 0
    tabs_owner, tab_feature_pages = _elect_tabs_owner(
        plan.get("routes", []), surface_index, plan.get("edges", [])
    )

    def _annotate(item: dict[str, Any], route_or_mount: str) -> None:
        nonlocal covered, blueprinted
        surface_id = item["surface_id"]
        summary = surface_index.get(surface_id)
        if summary:
            covered += 1
        hints = {
            "class_histogram": (summary or {}).get("class_histogram"),
            "content_descs": (summary or {}).get("content_descs"),
        }
        custom_reason = ""
        histogram = hints["class_histogram"]
        if isinstance(histogram, dict) and any(
            any(draw in str(cls) for draw in CUSTOM_DRAW_CLASSES) for cls in histogram
        ):
            matched = next(
                cls for cls in histogram
                if any(draw in str(cls) for draw in CUSTOM_DRAW_CLASSES)
            )
            custom_reason = (
                f"检测到自绘组件类 {matched}（系统组件无法表达，允许自定义绘制）"
            )
        structure = _android_structure_sentence(surface_id, summary)
        native_component = map_native_component(item["kind"], hints)
        matched_rule = _matched_rule(item["kind"], hints)
        if (
            item["kind"] == "page"
            and matched_rule == RULE_PAGE_TABS
            and tabs_owner is not None
            and surface_id != tabs_owner
        ):
            # 共享快照证据仲裁：Tab 特征词命中但唯一持有者是其它 page。
            matched_rule = RULE_PAGE_PLAIN
            native_component = map_native_component(item["kind"], {
                "class_histogram": None, "content_descs": None,
            })
            structure += (
                f"（Tab 特征词命中，但底栏 Tabs 唯一持有者为 {tabs_owner}"
                "——共享快照证据仲裁）"
            )
        item["android_structure"] = structure
        item["preserve"] = _preserve_contract(summary, global_palette)
        item["native_carrier"] = _native_carrier_note(route_or_mount)
        item["native_component"] = native_component
        item["matched_rule"] = matched_rule
        item["custom_allowed"] = "yes" if custom_reason else "no"
        item["reason"] = custom_reason
        blueprinted += 1

    for route in plan["routes"]:
        _annotate(route, "route")
    for modal in plan["modals"]:
        host = modal.get("host_surface_id")
        _annotate(modal, f"modal@{host}" if host else "modal@UNRESOLVED")
    for item in plan["passthrough"]:
        _annotate(item, "none")

    stats = plan.setdefault("stats", {})
    stats["ui_blueprint_surface_count"] = blueprinted
    stats["ui_blueprint_visual_memory_covered"] = covered
    summary_out = {
        "policy": "UI_FIDELITY=HIGH",
        "purpose": (
            "Android UI 在 HarmonyOS 上的原生表达决策（P3 冻结，"
            "Phase 4 按图施工，不临时发挥）"
        ),
        "mapping_rules": [
            "page+bottom-tabs -> Navigation+NavPathStack+Tabs(barPosition=End)+List+LazyForEach",
            "page+plain-content -> Navigation+NavPathStack+List/Scroll",
            "sheet -> bindSheet(detents MEDIUM/LARGE)",
            "dialog -> CustomDialog/bindMenu",
            "menu -> bindMenu",
            "container/component -> none (透传)",
        ],
        "tabs_owner_arbitration": {
            "rule": (
                "一个 Navigation 体系只有一个底栏 Tabs；多 page 共享同一"
                "快照证据时按 特征强度 > 主入口命名标记(HOME/MAIN/LAUNCHER)"
                " > nav 出度 > 字典序 仲裁唯一持有者"
            ),
            "tabs_owner_surface_id": tabs_owner,
            "tab_feature_page_ids": tab_feature_pages,
        },
        "custom_allowed_policy": (
            "默认 no；仅 class_histogram 出现自绘类（SurfaceView/TextureView/"
            "GLSurfaceView）判系统组件无法表达时 yes 并登记 reason"
        ),
        "visual_memory": visual_memory_source
        or {"available": visual_memory is not None},
        "stats": {
            "blueprinted_surface_count": blueprinted,
            "visual_memory_covered_surface_count": covered,
        },
    }
    plan["ui_blueprint"] = summary_out
    return summary_out


