def _norm_hex(value: Any) -> str | None:
    """色值规范化为 #RRGGBB / #AARRGGBB 大写；非法输入返回 None。"""
    if not isinstance(value, str):
        return None
    text = value.strip()
    if not text.startswith("#"):
        text = "#" + text
    body = text[1:]
    if len(body) == 3 and all(ch in "0123456789abcdefABCDEF" for ch in body):
        body = "".join(ch * 2 for ch in body)
    if len(body) not in (6, 8) or not all(ch in "0123456789abcdefABCDEF" for ch in body):
        return None
    return "#" + body.upper()


def _invert_hex(hex_value: str) -> str:
    """明色反演为暗色（HSL 亮度 L -> 1-L，保色相与饱和度；保留 alpha 通道）。

    仅用于色板缺失 Dark swatch 时的 dark 资源退化（摘要注明
    inverted-from-light），不用于已有 palette-dark 数据的 token。
    """
    body = hex_value.lstrip("#")
    if len(body) == 8:
        # #AARRGGBB 惯例：前两位 alpha，后六位 RGB（如 #66000000 = 40% 黑）
        alpha, rgb = body[:2], body[2:]
    else:
        alpha, rgb = None, body
    r, g, b = (int(rgb[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    hue, light, sat = colorsys.rgb_to_hls(r, g, b)
    r2, g2, b2 = colorsys.hls_to_rgb(hue, 1.0 - light, sat)
    inverted = f"{round(r2 * 255):02X}{round(g2 * 255):02X}{round(b2 * 255):02X}"
    return f"#{alpha.upper()}{inverted}" if alpha else f"#{inverted}"


def _palette_index(
    global_palette: dict[str, Any],
) -> tuple[dict[str, str], dict[str, str], dict[str, str], dict[str, str]]:
    """PALETTE swatches -> (light hex 索引, dark hex 索引, light 全名, dark 全名)。

    短名 = name 最后一段；name 含 'Dark' 归 dark 组（GlasenseDarkPalette.*）。
    background_colors / theme_colors 列表并入同索引（去重，先到先得）。
    全名索引用于 token 来源标注（swatch 名保真）。
    """
    light: dict[str, str] = {}
    dark: dict[str, str] = {}
    light_names: dict[str, str] = {}
    dark_names: dict[str, str] = {}

    def _absorb(name: Any, hex_value: Any) -> None:
        normalized = _norm_hex(hex_value)
        if not isinstance(name, str) or normalized is None:
            return
        # 常规 palette 名带前缀（GlasenseLightPalette.background）；裸 token
        # 名（Blue500）无点号，以全名兼作短名收录（供渐变 stops 解析）。
        short = name.rsplit(".", 1)[-1] if "." in name else name
        target = dark if "Dark" in name else light
        names = dark_names if "Dark" in name else light_names
        if short not in target:
            target[short] = normalized
            names[short] = name

    for swatch in global_palette.get("swatches") or []:
        if isinstance(swatch, dict) and swatch.get("kind") == "PALETTE":
            _absorb(swatch.get("name"), swatch.get("hex"))
    for swatch in global_palette.get("background_colors") or []:
        if isinstance(swatch, dict):
            _absorb(swatch.get("name"), swatch.get("hex"))
    for swatch in global_palette.get("theme_colors") or []:
        if isinstance(swatch, dict):
            _absorb(swatch.get("name"), swatch.get("hex"))
    return light, dark, light_names, dark_names


def _derive_gradient(global_palette: dict[str, Any]) -> dict[str, Any] | None:
    """挑选代表渐变（多 stop 优先，candidate 顺序），保留 stops 原始顺序。

    stops 为源码 token 引用（如 Blue500）：仅当每个 token 都能在 PALETTE
    索引中解析出 hex 时输出 hex 数组，否则保真 token 名并标 resolved=false
    （Phase 4 视觉修复轮按 theme 源码解析补值，不在此发明色值）。
    """
    light, dark, _, _ = _palette_index(global_palette)
    candidates = [
        swatch for swatch in (global_palette.get("swatches") or [])
        if isinstance(swatch, dict) and swatch.get("kind") == "GRADIENT"
        and isinstance(swatch.get("tokens"), list) and swatch["tokens"]
    ]
    if not candidates:
        return None
    multi = [s for s in candidates if len(s["tokens"]) > 1]
    chosen = (multi or candidates)[0]
    stops = [str(token) for token in chosen["tokens"]]
    hexes: list[str | None] = []
    for token in stops:
        resolved = light.get(token) or dark.get(token)
        hexes.append(resolved)
    origin = chosen.get("origin") if isinstance(chosen.get("origin"), dict) else {}
    return {
        "source_swatch": str(chosen.get("candidate_id") or chosen.get("name") or "gradient"),
        "source_name": str(chosen.get("name") or ""),
        "origin_ref": (
            f"{origin.get('file', '?')}:{origin.get('line', '?')}" if origin else "n/a"
        ),
        "stops": stops,
        "resolved_to_hex": all(hex_value is not None for hex_value in hexes),
        "hexes": hexes if all(hex_value is not None for hex_value in hexes) else None,
    }


def _derive_theme_tokens(visual_memory: dict[str, Any] | None) -> dict[str, Any]:
    """visual-memory -> 主题 token 集（纯函数：确定性、无 IO、可单测）。

    返回：light/dark 色值 + 每槽 source（swatch 全名 / platform-default /
    inverted:<light 来源>）+ 渐变 + 字号阶梯来源；dark 缺失槽由明色反演
    （dark_mode 记录 inverted-from-light；primary 无 swatch 时保持平台
    默认主色，不计为反演）。
    """
    source_map: dict[str, str] = {}
    dark_source_map: dict[str, str] = {}
    light_values: dict[str, str] = {}
    dark_values: dict[str, str] = {}
    used_inversion = False
    palette = (
        visual_memory.get("global_palette")
        if isinstance(visual_memory, dict)
        and isinstance(visual_memory.get("global_palette"), dict)
        else None
    )
    light_index, dark_index, light_names, dark_names = _palette_index(palette or {})
    for token_key, swatch_short in THEME_SWATCH_SLOTS:
        if swatch_short in light_index:
            light_values[token_key] = light_index[swatch_short]
            source_map[token_key] = light_names[swatch_short]
        else:
            light_values[token_key] = THEME_PLATFORM_DEFAULTS[token_key]
            source_map[token_key] = "platform-default"
        if swatch_short in dark_index:
            dark_values[token_key] = dark_index[swatch_short]
            dark_source_map[token_key] = dark_names[swatch_short]
        elif token_key == "primary":
            # primary 槽两侧都可能无 swatch：保持平台默认主色（不做反演，
            # 品牌主色明暗一致；来源注明 platform-default）。
            dark_values[token_key] = THEME_PLATFORM_DEFAULTS[token_key]
            dark_source_map[token_key] = "platform-default"
        else:
            dark_values[token_key] = _invert_hex(light_values[token_key])
            dark_source_map[token_key] = f"inverted:{source_map[token_key]}"
            used_inversion = True
    if not palette:
        dark_mode = THEME_MODE_DEFAULT
    elif used_inversion:
        dark_mode = THEME_DARK_INVERTED
    else:
        dark_mode = THEME_DARK_SWATCH
    gradient = _derive_gradient(palette or {}) if palette else None
    text_sizes = (
        visual_memory.get("text_sizes")
        if isinstance(visual_memory, dict)
        and isinstance(visual_memory.get("text_sizes"), dict)
        else {}
    )
    sizes_data = text_sizes.get("sizes") if isinstance(text_sizes.get("sizes"), dict) else None
    typography: dict[str, int] = dict(THEME_TYPOGRAPHY_LADDER)
    typography_source = "platform-standard-ladder"
    if text_sizes.get("available") is True and sizes_data:
        for ladder_key in typography:
            value = sizes_data.get(ladder_key)
            if isinstance(value, (int, float)):
                typography[ladder_key] = int(value)
        typography_source = "visual-memory-text-sizes"
    return {
        "mode": THEME_MODE_PALETTE if palette else THEME_MODE_DEFAULT,
        "light": light_values,
        "dark": dark_values,
        "dark_mode": dark_mode,
        "source_map": source_map,
        "dark_source_map": dark_source_map,
        "gradient": gradient,
        "typography": typography,
        "typography_source": typography_source,
        "typography_note": str(text_sizes.get("note") or ""),
        "text_sizes_available": text_sizes.get("available") is True,
        "swatch_count": int(palette.get("swatch_count") or 0) if palette else 0,
    }


def _render_app_theme(tokens: dict[str, Any], meta: dict[str, Any]) -> str:
    """token 集 -> AppTheme.ets（确定性渲染；每 token 行尾注明来源）。"""
    light, dark = tokens["light"], tokens["dark"]
    source_map = tokens["source_map"]
    dark_source_map = tokens["dark_source_map"]
    gradient = tokens["gradient"]
    lines: list[str] = []
    lines.append(
        "// Design tokens generated deterministically by init_scaffold"
        " (emit_theme_layer) from the"
    )
    lines.append(f"// Phase 2 visual memory: {meta['visual_memory_path']}")
    if tokens["mode"] == THEME_MODE_PALETTE:
        lines.append(
            f"// Palette basis: global ({tokens['swatch_count']} swatches); every color"
            " token annotates its source"
        )
        lines.append("// swatch name inline. Slots without palette data fall back to")
        lines.append("// platform defaults and are annotated as platform-default.")
    else:
        lines.append(
            "// visual-memory.json was NOT available: all tokens fall back to platform"
        )
        lines.append("// defaults (annotated platform-default); the Phase 4 visual pass")
        lines.append("// may re-derive tokens once visual memory exists. Scaffold is not blocked.")
    if not tokens["text_sizes_available"]:
        lines.append("// Typography: visual-memory has no font-size data")
        lines.append(f"// (text_sizes.available=false: {tokens['typography_note'] or 'n/a'})")
        lines.append("// values follow the platform standard ladder in fp units.")
    else:
        lines.append("// Typography: derived from visual-memory text_sizes (fp units).")
    lines.append(
        "// Spacing/radius: platform standard ladders (uiautomator key_bounds carries"
    )
    lines.append(
        "// bounds only, no corner-radius attribute; radius values follow platform"
    )
    lines.append("// guidance scaled to key_bounds control sizes)."
    )
    lines.append("")
    lines.append("export class AppTheme {")
    lines.append("  // ---- colors (light + dark variants; sources annotated inline) ----")
    lines.append("  static readonly colors: Record<string, string> = {")
    for token_key, _ in THEME_SWATCH_SLOTS:
        lines.append(
            f"    {token_key}: '{light[token_key]}',  // {source_map[token_key]}"
        )
    for token_key, _ in THEME_SWATCH_SLOTS:
        lines.append(
            f"    {token_key}Dark: '{dark[token_key]}',  // {dark_source_map[token_key]}"
        )
    lines.append("  }")
    lines.append("")
    if gradient:
        lines.append("  // ---- gradients (stops order preserved from source) ----")
        lines.append(
            f"  // source swatch: {gradient['source_swatch']} ({gradient['source_name']})"
            f" @ {gradient['origin_ref']}"
        )
        if gradient["resolved_to_hex"]:
            stops_literal = ", ".join(f"'{value}'" for value in gradient["hexes"])
            lines.append(
                f"  static readonly gradients: Record<string, string[]> = {{ accent: [{stops_literal}] }}"
                "// hex stops resolved from palette"
            )
        else:
            stops_literal = ", ".join(f"'{token}'" for token in gradient["stops"])
            lines.append(
                f"  static readonly gradients: Record<string, string[]> = {{ accentTokens: [{stops_literal}] }}"
            )
            lines.append(
                "    // stops are source token references: visual-memory carries no token->hex"
            )
            lines.append(
                "    // resolution; Phase 4 visual pass resolves them via the Android theme source."
            )
    else:
        lines.append("  // ---- gradients (none in visual memory) ----")
        lines.append("  static readonly gradients: Record<string, string[]> = { accentTokens: [] }")
    lines.append("")
    lines.append("  // ---- typography ladder (fp) ----")
    lines.append("  static readonly typography: Record<string, number> = {")
    for ladder_key, value in tokens["typography"].items():
        lines.append(f"    {ladder_key}: {value},")
    lines.append("  }")
    lines.append("")
    lines.append("  // ---- spacing ladder (vp) ----")
    lines.append("  static readonly spacing: Record<string, number> = {")
    for ladder_key, value in THEME_SPACING_LADDER.items():
        lines.append(f"    {ladder_key}: {value},")
    lines.append("  }")
    lines.append("")
    lines.append("  // ---- radius ladder (vp) ----")
    lines.append("  static readonly radius: Record<string, number> = {")
    for ladder_key, value in THEME_RADIUS_LADDER.items():
        lines.append(f"    {ladder_key}: {value},")
    lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _render_color_resources(tokens: dict[str, Any]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """token 集 -> (base 条目, dark 条目)（HarmonyOS element/color.json 结构）。"""
    base_entries = [
        {"name": THEME_RESOURCE_NAMES[key], "value": tokens["light"][key]}
        for key, _ in THEME_SWATCH_SLOTS
    ]
    dark_entries = [
        {"name": THEME_RESOURCE_NAMES[key], "value": tokens["dark"][key]}
        for key, _ in THEME_SWATCH_SLOTS
    ]
    return base_entries, dark_entries


def _locate_visual_memory(
    workspace: Path, input_lock: dict[str, Any]
) -> tuple[Path | None, list[str]]:
    """visual-memory.json 定位：input-lock inputs 推导优先，phase2 工作区次之。"""
    tried: list[str] = []
    candidates: list[Path] = []
    inputs = input_lock.get("inputs") if isinstance(input_lock.get("inputs"), dict) else {}
    feature_map_entry = inputs.get("feature_map") if isinstance(inputs.get("feature_map"), dict) else {}
    feature_map_path = str(feature_map_entry.get("path") or "")
    if feature_map_path:
        candidates.append(Path(feature_map_path).resolve().parent / "visual-memory.json")
    candidates.append(workspace.parent / PHASE2_WORKSPACE_NAME / "visual-memory.json")
    for candidate in candidates:
        tried.append(str(candidate))
        if candidate.is_file() and not candidate.is_symlink():
            return candidate, tried
    return None, tried


def emit_theme_layer(workspace: Path, input_lock: dict[str, Any]) -> dict[str, Any]:
    """主题层入口：派生 token 并写入骨架工程 + surface-plan 摘要（幂等可重放）。

    产物（相对 workspace/harmony-project）：
    - entry/src/main/ets/foundation/AppTheme.ets
    - entry/src/main/resources/{base,dark}/element/color.json
    surface-plan.json（存在且合法时）追加 theme_tokens 摘要。visual-memory
    缺失时全部退化为平台默认（mode=platform-default），不阻塞骨架。
    """
    workspace = Path(workspace)
    visual_memory_path, tried = _locate_visual_memory(workspace, input_lock)
    visual_memory: dict[str, Any] | None = None
    visual_memory_sha256: str | None = None
    if visual_memory_path is not None:
        try:
            loaded = load_json(visual_memory_path)
        except ValueError:
            loaded = None
        if isinstance(loaded, dict):
            visual_memory = loaded
            visual_memory_sha256 = sha256_file(visual_memory_path)
    tokens = _derive_theme_tokens(visual_memory)
    meta = {
        "visual_memory_path": (
            str(visual_memory_path) if visual_memory_path is not None
            else f"not found (tried: {', '.join(tried)})"
        ),
    }
    project_root = workspace / "harmony-project"
    base_entries, dark_entries = _render_color_resources(tokens)
    atomic_text(project_root / THEME_FOUNDATION_FILE, _render_app_theme(tokens, meta))
    atomic_json(project_root / THEME_COLOR_BASE_FILE, {"color": base_entries})
    atomic_json(project_root / THEME_COLOR_DARK_FILE, {"color": dark_entries})
    summary: dict[str, Any] = {
        "generated_by": "emit_theme_layer",
        "mode": tokens["mode"],
        "visual_memory": {
            "path": str(visual_memory_path) if visual_memory_path else None,
            "sha256": visual_memory_sha256,
            "available": visual_memory is not None,
        },
        "color_token_count": len(THEME_SWATCH_SLOTS) * 2,
        "resource_color_count": len(THEME_RESOURCE_NAMES),
        "dark_mode": tokens["dark_mode"],
        "gradient": tokens["gradient"],
        "typography": {
            "source": tokens["typography_source"],
            "ladder": tokens["typography"],
            "text_sizes_available": tokens["text_sizes_available"],
        },
        "spacing": {"source": "platform-standard-ladder", "ladder": THEME_SPACING_LADDER},
        "radius": {
            "source": "platform-guidance (key_bounds carries no corner-radius attribute)",
            "ladder": THEME_RADIUS_LADDER,
        },
        "files": {
            "app_theme": THEME_FOUNDATION_FILE,
            "color_base": THEME_COLOR_BASE_FILE,
            "color_dark": THEME_COLOR_DARK_FILE,
        },
        "source_map": tokens["source_map"],
    }
    plan_path = workspace / "surface-plan.json"
    if plan_path.is_file():
        try:
            plan = load_json(plan_path)
        except ValueError:
            plan = None
        if isinstance(plan, dict):
            plan["theme_tokens"] = summary
            atomic_json(plan_path, plan)
    return summary


